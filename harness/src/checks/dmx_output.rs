/// A CMY head in the `.fixture` form: cyan 1, magenta 2, yellow 3, no
/// dimmer, so it compares byte for byte with [`RGB_PAR`].
const CMY_HEAD: &str = "# Generated by the mtrack hardware e2e suite.\n\
fixture_type \"E2E_CmyHead\" {\n  channel \"cyan\" @ 1\n  channel \"magenta\" @ 2\n  \
channel \"yellow\" @ 3\n}\n";

/// The same head with its flags declared as red, green and blue: the
/// self-test's control, a head the engine drives as an RGB fixture, so its
/// bytes are the colour rather than its complement.
const CMY_HEAD_AS_RGB: &str = "# Generated by the mtrack hardware e2e suite.\n\
fixture_type \"E2E_CmyHead\" {\n  channel \"red\" @ 1\n  channel \"green\" @ 2\n  \
channel \"blue\" @ 3\n}\n";

/// Where the colour pair sits: the RGB-only par at 1-3, the CMY head at 5-7.
const PAIR_RGB_AT: u16 = 1;
const PAIR_CMY_AT: u16 = 5;

/// The RGB par's (r, g, b) and the CMY head's (c, m, y) as the wire has them.
fn colour_pair(frame: &Frame) -> ([u8; 3], [u8; 3]) {
    let three = |at: u16| {
        [
            frame.channel(at),
            frame.channel(at + 1),
            frame.channel(at + 2),
        ]
    };
    (three(PAIR_RGB_AT), three(PAIR_CMY_AT))
}

/// A colour is the same colour on an RGB par and a CMY head: the head's
/// flags are exactly the complement of the par's bytes, for a hex colour,
/// a named one, and one given in CMY with `cmy()` (#780, #783).
///
/// One song cues three colours on a group holding both fixtures, three
/// seconds each: web pink `#FFC0CB` (255, 192, 203; flags 0, 63, 52), red
/// (flags 0, 255, 255), and `cmy(20%, 60%, 0%)`, which prints as (204, 102,
/// 255) and puts its inks on the head as written: 20% and 60% of 255 are 51
/// and 153.
pub async fn a_colour_is_the_same_colour_on_an_rgb_par_and_a_cmy_head() -> CheckOutcome {
    crate::runner::require_area("dmx-output")?;
    let show = show_file(
        "CMY Show",
        "",
        &format!(
            "    @00:00.000\n    \
             {LIGHTING_GROUP}: static color: \"#FFC0CB\", duration: 3s\n    \
             @00:03.000\n    \
             {LIGHTING_GROUP}: static color: \"red\", duration: 3s\n    \
             @00:06.000\n    \
             {LIGHTING_GROUP}: static color: cmy(20%, 60%, 0%), duration: 4s\n"
        ),
    );
    let song = SongSpec::tones("CMY Song", "cmy-song", 1, 12.0).with_lighting(show);
    let venue = format!(
        "venue \"{VENUE}\" {{\n  \
         fixture \"Rgb1\" E2E_RgbPar @ 1:{PAIR_RGB_AT} tags [\"wash\"]\n  \
         fixture \"Cmy1\" E2E_CmyHead @ 1:{PAIR_CMY_AT} tags [\"wash\"]\n}}\n"
    );
    // The control breaks the world, not the reading: the head is declared
    // with RGB channels, so a check that compared nothing would still pass.
    let head = crate::sabotage::pick(CMY_HEAD, CMY_HEAD_AS_RGB);
    let project = ProjectBuilder::new()
        .profiles(vec![ProfileSpec::detected("01-e2e")
            .with_lighting()
            .with_venue(VENUE)])
        .songs(vec![song])
        .lighting_file("lighting/fixture_types/e2e_rgb_par.light", RGB_PAR)
        .lighting_file("lighting/fixture_types/e2e_cmy_head.fixture", head)
        .lighting_file("lighting/venues/e2e_dmx.venue", &venue)
        .build()?;
    let server = Server::start(&project).await?;
    let mut client = Client::connect(&server).await?;
    // Every colour here has full red, so the par's red is up from the start.
    let sink = play_and_sink(&server, &mut client, PAIR_RGB_AT).await?;
    let started = std::time::Instant::now();

    let mut seen = Vec::new();
    for at in [1000, 4000, 7000] {
        tokio::time::sleep(Duration::from_millis(at).saturating_sub(started.elapsed())).await;
        seen.push(colour_pair(&settled(&sink).await?));
    }
    client.grpc().stop(StopRequest {}).await?;

    crate::outcome::record(format!(
        "RGB par / CMY head: pink {:?} / {:?}; red {:?} / {:?}; cmy(20%, 60%, 0%) {:?} / {:?}",
        seen[0].0, seen[0].1, seen[1].0, seen[1].1, seen[2].0, seen[2].1
    ));
    let cues = [
        ("\"#FFC0CB\"", [255, 192, 203], [0, 63, 52]),
        ("\"red\"", [255, 0, 0], [0, 255, 255]),
        ("cmy(20%, 60%, 0%)", [204, 102, 255], [51, 153, 0]),
    ];
    for ((cue, want_rgb, want_cmy), (rgb, cmy)) in cues.into_iter().zip(seen) {
        check!(
            near(rgb, want_rgb, 1),
            "{cue} on the RGB par should be {want_rgb:?}; the wire had {rgb:?}"
        );
        check!(
            near(cmy, want_cmy, 1),
            "{cue} on the CMY head should be the flags {want_cmy:?}; the wire had {cmy:?}. \
             The par's own bytes there mean the head was driven as if it mixed RGB"
        );
        check!(
            cmy == rgb.map(|b| 255 - b),
            "{cue}: the CMY head's flags {cmy:?} should be exactly the complement of the RGB \
             par's {rgb:?}, read off the same frame"
        );
    }
    server.check_clean_log(&[])?;
    Ok(())
}
