// Builds the player's tempo map (crates/mtrack-tempo-wasm, which compiles
// src/tempo.rs) to WebAssembly and writes it into src/gen/tempo-wasm.ts, as
// a base64 string the UI instantiates (src/lib/tempo-wasm.ts). Embedded
// rather than fetched, so the same module loads in the browser, in the Vite
// dev server and in Node (the Playwright tests import the timeline's math
// directly), with nothing for the server to serve.
//
// Needs cargo and the wasm32-unknown-unknown target:
//   rustup target add wasm32-unknown-unknown

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..", "..");
const crate = "mtrack-tempo-wasm";
const target = "wasm32-unknown-unknown";

const cargo = process.env.CARGO ?? "cargo";
execFileSync(
  cargo,
  ["build", "--release", "--locked", "--target", target, "-p", crate],
  { cwd: root, stdio: "inherit" },
);
const metadata = JSON.parse(
  execFileSync(cargo, ["metadata", "--format-version", "1", "--no-deps"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }),
);
const wasm = readFileSync(
  join(
    metadata.target_directory,
    target,
    "release",
    `${crate.replaceAll("-", "_")}.wasm`,
  ),
);

/** The module without its custom sections (names, producers): nothing the
 *  page runs needs them. */
function stripCustomSections(bytes) {
  const out = [bytes.subarray(0, 8)];
  let i = 8;
  while (i < bytes.length) {
    const start = i;
    const id = bytes[i++];
    let size = 0;
    let shift = 0;
    for (;;) {
      const b = bytes[i++];
      size |= (b & 0x7f) << shift;
      shift += 7;
      if (b < 0x80) break;
    }
    i += size;
    if (id !== 0) out.push(bytes.subarray(start, i));
  }
  return Buffer.concat(out);
}

const stripped = stripCustomSections(wasm);
const outDir = join(here, "..", "src", "gen");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "tempo-wasm.ts"),
  `// Generated by scripts/build-tempo-wasm.mjs from crates/${crate}. Do not edit.\n` +
    `export const TEMPO_WASM = "${stripped.toString("base64")}";\n`,
);
console.log(
  `tempo wasm: ${stripped.length} bytes (${wasm.length} before stripping)`,
);
